// Simplify the measured exterior into a schematic, symmetric silhouette.
// Source geometry and CC BY 2.5 attribution: data/cathedral-contours.json.
import {readFileSync,writeFileSync} from 'node:fs';
import vm from 'node:vm';
const base=new URL('../',import.meta.url);
const source=JSON.parse(readFileSync(new URL('data/cathedral-contours.json',base),'utf8'));
const sandbox={window:{}};
vm.runInNewContext(readFileSync(new URL('assets/math-network.js',base),'utf8'),sandbox);
const spain=sandbox.window.personalSiteMathNetwork;
const width=800,height=900,count=spain.nodes.length;
// Discard every interior/window contour. Use the photographed exterior only,
// taking its top envelope to remove recesses and incidental image noise.
const exterior=source.paths[0],xs=exterior.map(p=>p[0]),ys=exterior.map(p=>p[1]);
const left=Math.min(...xs),right=Math.max(...xs),bottom=Math.max(...ys);
const centralPeak=exterior.filter(([x])=>x>left+(right-left)*.42&&x<left+(right-left)*.53)
  .reduce((a,b)=>a[1]<b[1]?a:b);
const axis=centralPeak[0],skyline=[];
for(let x=left;x<=axis;x++){
  const crossings=[];
  for(let i=1;i<exterior.length;i++){
    const a=exterior[i-1],b=exterior[i];
    if(x<Math.min(a[0],b[0])||x>Math.max(a[0],b[0]))continue;
    crossings.push(a[0]===b[0]?Math.min(a[1],b[1]):a[1]+(b[1]-a[1])*(x-a[0])/(b[0]-a[0]));
  }
  if(crossings.length)skyline.push([x,Math.min(...crossings)]);
}
// A short median filter removes tiny stone ornaments; a coarse geometric
// simplification keeps the tower crowns and central peak without tracing them.
const smooth=skyline.map(([x],i)=>{
  const y=skyline.slice(Math.max(0,i-3),i+4).map(p=>p[1]).sort((a,b)=>a-b);
  return [x,y[Math.floor(y.length/2)]];
});
function distance(p,a,b){
  const dx=b[0]-a[0],dy=b[1]-a[1];
  const t=Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/(dx*dx+dy*dy||1)));
  return Math.hypot(p[0]-a[0]-t*dx,p[1]-a[1]-t*dy);
}
function simplify(points){
  let farthest=0,index=0;
  for(let i=1;i<points.length-1;i++){
    const d=distance(points[i],points[0],points.at(-1));
    if(d>farthest){farthest=d;index=i}
  }
  return farthest>6?[...simplify(points.slice(0,index+1)).slice(0,-1),...simplify(points.slice(index))]:[points[0],points.at(-1)];
}
const half=simplify(smooth);
// Mirror the measured left profile to remove the photograph's tilted view.
// Close with straight sides/base instead of tracing doors, statues or stairs.
const outline=[[left,bottom],...half,...half.slice(0,-1).reverse().map(([x,y])=>[2*axis-x,y]),[2*axis-left,bottom],[left,bottom]];
const bounds={left,right:2*axis-left,top:Math.min(...outline.map(p=>p[1])),bottom};
const scale=Math.min((width-90)/(bounds.right-bounds.left),(height-80)/(bounds.bottom-bounds.top));
const project=([x,y])=>[(x-(bounds.left+bounds.right)/2)*scale+width/2,(y-(bounds.top+bounds.bottom)/2)*scale+height/2];
const paths=[outline.map(project)];
const length=path=>path.slice(1).reduce((sum,p,i)=>sum+Math.hypot(p[0]-path[i][0],p[1]-path[i][1]),0);
const lengths=paths.map(length);
const allocation=[count];
const nodes=[],connections=[],tangents=[];
paths.forEach((path,p)=>{
  const start=nodes.length,n=allocation[p],segments=path.slice(1).map((b,i)=>({a:path[i],b,length:Math.hypot(b[0]-path[i][0],b[1]-path[i][1])}));
  let segment=0,travelled=0;
  for(let i=0;i<n;i++){
    const distance=lengths[p]*i/n;
    while(segment<segments.length-1&&travelled+segments[segment].length<distance)travelled+=segments[segment++].length;
    const {a,b,length:l}=segments[segment],t=(distance-travelled)/(l||1);
    nodes.push([a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t].map(v=>Number(v.toFixed(3))));
    tangents.push(Math.atan2(b[1]-a[1],b[0]-a[0]));
    connections.push([start+i,start+(i+1)%n]);
  }
});
if(nodes.length!==count)throw new Error('The cathedral and Spain must share particle identities.');
const vectorAngles=spain.vectors.map(v=>tangents[v.node]);
const graph={width,height,nodes,connections,vectorAngles};
const credit='Cathedral silhouette adapted from Santiago.de.Compostela.Catedral.Noche.jpg by Yearofthedragon, CC BY 2.5, via Wikimedia Commons. Exterior simplified, mirrored for a schematic front view and sampled into one particle outline; all interior details omitted.';
writeFileSync(new URL('assets/cathedral-network.js',base),`// Generated by scripts/generate-cathedral.mjs.\n// ${credit}\n// ${source.source.url}\n// ${source.source.licenseUrl}\nwindow.personalSiteCathedralNetwork = ${JSON.stringify(graph)};\n`);
const f=n=>Number(n.toFixed(2));
const lines=connections.map(([i,j])=>`M${nodes[i].map(f).join(',')}L${nodes[j].map(f).join(',')}`).join('');
const dots=nodes.map(([x,y],i)=>`<circle cx="${f(x)}" cy="${f(y)}" r="${i%11===0?1.7:.95}"/>`).join('');
writeFileSync(new URL('assets/cathedral-network.svg',base),`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" fill="none">
<title>Santiago de Compostela Cathedral silhouette</title>
<desc>A schematic outer silhouette with two balanced towers and a central peak, without facade details. ${credit} Source: ${source.source.url} License: ${source.source.licenseUrl}</desc>
<path d="${lines}" stroke="#647a8b" stroke-width=".7" opacity=".4"/>
<g fill="#647a8b" opacity=".5">${dots}</g>
</svg>\n`);
console.log(`Generated schematic cathedral silhouette: ${nodes.length} particles on one exterior outline with ${outline.length-1} simplified corners; no facade details.`);
